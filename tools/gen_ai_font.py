"""Generate a host GB2312 atlas and a tiny FPGA submenu font ROM."""
import argparse
import json
from pathlib import Path
import sys
from PIL import ImageFont
from gen_font_rom import render_glyph


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--font', default='C:/Windows/Fonts/simhei.ttf')
    root=Path(__file__).resolve().parents[1]
    ap.add_argument('--out', type=Path, default=root/'rtl/common/ai_menu_font.v')
    ap.add_argument('--atlas', type=Path, default=root/'host/ai_coordinator/ai_font_rows.json')
    args = ap.parse_args()
    font = ImageFont.truetype(args.font, 16)
    count = 95 + 87*94
    args.out.parent.mkdir(parents=True, exist_ok=True)
    rows=[]
    for index in range(count):
        if index<95:char=chr(index+32)
        else:
            n=index-95
            try:char=bytes((0xa1+n//94,0xa1+n%94)).decode('gb2312')
            except UnicodeError:char=' '
        rows.append(render_glyph(char,font,16))
    args.atlas.parent.mkdir(parents=True,exist_ok=True)
    args.atlas.write_text(json.dumps({'format':'ascii-gb2312-16x16','glyphs':rows},separators=(',',':'))+'\n',encoding='utf-8')
    with args.out.open('w',encoding='utf-8',newline='\n') as f:
        f.write('// Generated by tools/gen_ai_font.py; local submenu only.\n')
        f.write('module ai_menu_font(input wire clk,input wire [8:0] addr,output reg [23:0] bits);\n')
        text='语义导航目标识别聊天机器人 '
        menu_font=ImageFont.truetype(args.font,24)
        f.write('reg [23:0] mem [0:%d];\ninitial begin\n'%(len(text)*24-1))
        for index,char in enumerate(text):
            for row,value in enumerate(render_glyph(char,menu_font,24)):
                f.write("mem[%d]=24'h%06x;\n"%(index*24+row,value))
        f.write("end\nalways @(posedge clk) bits<=addr<%d?mem[addr]:24'd0;\nendmodule\n"%(len(text)*24))
    print('Generated host atlas',args.atlas,'and local menu ROM',args.out)


if __name__ == '__main__':
    main()
